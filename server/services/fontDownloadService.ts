import JSZip from 'jszip'
import { dbStore } from '~/server/utils/mockStore'
import { FontStorageService } from './fontStorageService'
import { FontLicensingService } from './fontLicensingService'

export interface DownloadResult {
  buffer: Buffer
  contentType: string
  fileName: string
}

export class FontDownloadService {
  /**
   * Generates a download for either a single font file or the complete family ZIP bundle
   */
  public static async prepareDownload(
    familySlugOrId: string,
    fileId?: string
  ): Promise<DownloadResult> {
    const family = Array.from(dbStore.fontFamilies.values()).find(
      f => f.slug === familySlugOrId || f.id === familySlugOrId
    )

    if (!family) {
      throw new Error(`Font family "${familySlugOrId}" not found`)
    }

    // License safety check
    const licenseProfile = FontLicensingService.inspectLicense(family.license_type)
    if (licenseProfile.category === 'RESTRICTED') {
      throw new Error(`Download restricted: Font family "${family.name}" is subject to commercial licensing terms.`)
    }

    const files = Array.from(dbStore.fontFiles.values()).filter(f => f.family_id === family.id)
    if (files.length === 0) {
      throw new Error(`No font files available for family "${family.name}"`)
    }

    // 1. Single file download
    if (fileId) {
      const file = files.find(f => f.id === fileId)
      if (!file) {
        throw new Error(`Font file ID "${fileId}" not found in family "${family.name}"`)
      }

      const fileBuffer = await FontStorageService.retrieveFontBuffer(file.storage_path)
      const mimeType = this.getMimeType(file.file_format)

      // Audit log download
      dbStore.auditLogs.push({
        id: `aud-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
        actor_id: 'anonymous',
        action: 'DOWNLOAD_FONT_FILE',
        entity_type: 'FONT_FILE',
        entity_id: file.id,
        metadata: { familyId: family.id, fileName: file.file_name, format: file.file_format },
        ip_address: '127.0.0.1',
        created_at: new Date().toISOString(),
      })

      return {
        buffer: fileBuffer,
        contentType: mimeType,
        fileName: file.file_name,
      }
    }

    // 2. Full Family ZIP bundle
    const zip = new JSZip()
    const folder = zip.folder(family.slug) || zip

    for (const f of files) {
      try {
        const fileBuffer = await FontStorageService.retrieveFontBuffer(f.storage_path)
        folder.file(f.file_name, fileBuffer)
      } catch (err) {
        console.warn(`[FontDownloadService] Could not include file ${f.file_name}:`, err)
      }
    }

    // Add README / LICENSE metadata text file
    const readmeContent = `=======================================================
${family.display_name || family.name} — Digital Font Bundle
=======================================================

Family: ${family.name}
Designer: ${family.designer || 'Unknown'}
Foundry: ${family.foundry || 'Unknown'}
License: ${family.license_type}
License URL: ${family.license_url || 'https://openfontlicense.org'}
Category: ${family.primary_category} ${family.arabic_style ? `(${family.arabic_style})` : ''}
Files Count: ${files.length}

Generated by Digital Assets Platform Font Engine (Phase 6)
Website: https://platform.example.com/fonts/${family.slug}
=======================================================
`
    folder.file('README.txt', readmeContent)

    const zipBuffer = await zip.generateAsync({
      type: 'nodebuffer',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 },
    })

    // Audit log family download
    dbStore.auditLogs.push({
      id: `aud-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
      actor_id: 'anonymous',
      action: 'DOWNLOAD_FONT_FAMILY_ZIP',
      entity_type: 'FONT_FAMILY',
      entity_id: family.id,
      metadata: { slug: family.slug, filesCount: files.length, zipSize: zipBuffer.length },
      ip_address: '127.0.0.1',
      created_at: new Date().toISOString(),
    })

    return {
      buffer: zipBuffer,
      contentType: 'application/zip',
      fileName: `${family.slug}-font-bundle.zip`,
    }
  }

  private static getMimeType(format: string): string {
    const f = format.toLowerCase()
    switch (f) {
      case 'woff2':
        return 'font/woff2'
      case 'woff':
        return 'font/woff'
      case 'otf':
        return 'font/otf'
      case 'ttf':
      default:
        return 'font/ttf'
    }
  }
}
